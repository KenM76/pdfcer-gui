@dataclass(frozen=True)
class EngineAsset:
    """An asset directory in `D:\\Dev\\pdfcer` that THIS binary redistributes.

    The engine is a separate repository with its own packaging, so nothing in
    its tree knows that pdfcer-gui ships its assets too. This list is that
    knowledge, written down where the gate can act on it.

    `how` is either:

    * ``"linked"`` — the files are compiled into `pdfcer-gui.exe` (an
      `include_bytes!` in a path dependency, statically linked). They ship
      whether or not the packager does anything.
    * ``"copied"`` — the files must be copied into the portable folder as
      loose files, so `tools/package-portable.py` has to carry them. The gate
      cross-checks that they are in `PAYLOAD_ASSET_DIRS`; a "copied" entry the
      packager does not know about is an asset that is attributed and then
      never shipped, which is a different kind of wrong from the usual one.
    """

    #: Path relative to the engine repository root, forward-slashed.
    path: str
    #: "linked" or "copied" — see the class docstring.
    how: str
    #: Why this binary redistributes it. Prose, for the failure message.
    why: str


#: Engine asset directories `pdfcer-gui.exe` redistributes.
#:
#: ★ THE SECOND ENTRY ARRIVED 2026-08-14, AND IS WHY THIS GATE WAS BUILT.
#:
#: `crates/pdfcer-core/assets/models/ocrs` — the CC-BY-SA-4.0 OCR model weights,
#: 12,240,008 bytes over two `.rten` files, accepted into the MIT portable
#: folder by the operator on 2026-08-14. It is `how="copied"` rather than
#: `how="linked"`: `pdfcer_core::ocr::models::resolve_model_dir` resolves them
#: from a `models/<engine>` directory beside the executable, so they are loose
#: files in the portable folder and the packager has to put them there.
#:
#: That declaration is load-bearing in **both** directions, which is the whole
#: shape this gate was written for. `how="copied"` makes check 6b demand an
#: entry in `PAYLOAD_ASSET_DIRS` — an attribution for files nobody receives is
#: as wrong as files received with no attribution — while checks 4 and 5 demand
#: the notice and the About dialog. Declaring the asset and forgetting any one
#: of the three fails here rather than shipping.

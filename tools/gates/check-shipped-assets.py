#!/usr/bin/env python3
"""Every non-Cargo file pdfcer-gui REDISTRIBUTES must have its licence recorded,
and that record must reach the person who was handed the binary.

A PORT of `D:\\Dev\\pdfcer\\tools\\check-shipped-assets.py`. Its reasoning is the
valuable part and is preserved below; what changed is marked "PORT CHANGE".
Read the original before editing this one — it is the specification.

WHY THIS GATE EXISTS
====================

`THIRD_PARTY_LICENSES.md` is generated by `cargo-about` from `Cargo.lock`. It
is complete and correct for what it covers, and it is **structurally
incapable** of covering anything that is not a Cargo dependency. Fonts, icons,
data tables, and — imminently — OCR model weights are files pdfcer ships inside
its portable folder or compiles into its executable, so they are redistributed
by pdfcer and carry whatever obligations their licences impose. `cargo-about`
cannot see any of them.

That is not a flaw in `cargo-about`; it is a gap between two tools, and a gap
between tools is exactly where an obligation goes missing without anyone
deciding to drop it.

WHY IT ARRIVED HERE, WHICH IS ITSELF THE FINDING
================================================

Until 2026-08-14 **this repository had no attribution surface of any kind** —
no `PROVENANCE.md`, no `cargo-about`, no third-party licence text anywhere in
the program or the package. That was defensible while pdfcer-gui shipped only
permissively-licensed *code*, whose notices the `LICENSE` file and the Cargo
metadata cover.

It stopped being defensible when the operator decided on 2026-08-14 to ship
the `ocrs` OCR model weights, which are **CC-BY-SA-4.0**. That licence's BY
clause requires the notice to reach the **end user**, not merely a reader of
the source tree — which is the whole distinction this gate is built around and
the reason check 4 exists.

Building the surface then turned up something nobody had gone looking for:
**three third-party works this binary already redistributes**, with no notice
anywhere. `pdfcer-render`'s `font::bundled` embeds fourteen BSD-3-Clause CFF
faces with `include_bytes!`, and `pdfcer-core`'s `fontdata::tables` compiles in
Adobe metric and glyph-list data. They arrive through path dependencies and
static linking, so they are inside `pdfcer-gui.exe` whether or not anyone in
this repository thought about them. The gate covers them explicitly — see
`REDISTRIBUTED_ENGINE_ASSETS`.

WHAT IT CHECKS
==============

For every asset directory this workspace redistributes — its own, under
`crates/**/assets/`, and the engine directories declared below:

1. A `PROVENANCE.md` exists.
2. That file NAMES A LICENCE — it must contain a recognisable licence
   identifier or an explicit statement of terms. A provenance note that says
   where files came from but not what may be done with them does not discharge
   anything.
3. Every shipped file in the directory is accounted for: at least one of the
   files actually present must be named, unless the note explicitly states it
   covers the whole directory.
4. ★ The directory is cited in **`about.hbs`**, the `cargo-about` template.
5. ★ PORT CHANGE — the directory is also cited in
   **`crates/pdfcer-gui/src/text/about.rs`**, the in-application surface.

Checks 4 and 5 are the ones that reach the OPERATOR rather than the
repository. `PROVENANCE.md` records terms for whoever reads the source tree;
it does NOT ship.

`about.hbs` is where the packaged half is fixed: it is the handlebars template
`cargo-about` renders, so a hand-written section in its static epilogue flows
into the generated `THIRD_PARTY_LICENSES.md` and therefore into every release.

★ WHY THIS PORT ADDS A FIFTH CHECK, WHEN THE ENGINE MANAGES WITH FOUR
=====================================================================

Because the engine is a CLI and this is a GUI, and the difference is not
cosmetic.

pdfcer's shipped notice is a file in a folder, and a CLI operator is already in
that folder — they got there to run the executable. A GUI operator may never
see it: they launch from a shortcut or a file association, and the folder is
somewhere a support engineer would have to talk them into opening. A `.md`
file is also one tidy-up away from being deleted by someone who does not know
what it is.

So this shell carries **both** surfaces — the file in the package, and an
About dialog reachable from File ▸ pdfcer — and the gate requires both,
because a change that remembers one and forgets the other is the commonest way
an obligation half-lands. The two are not redundant: the file carries the
licence TEXTS, which a dialog cannot reasonably render; the dialog carries the
ATTRIBUTION, which is what BY actually asks be given to the recipient.

Note what is NOT claimed here: that a UI surface is legally required. A notice
file shipped alongside is the ordinary way this obligation is discharged. The
second surface is a product judgement — the operator asked for the model to
ship *"with proper credit"* — and having built it, the gate keeps it true.

**Own work is exempt from 4 and 5.** An asset whose `PROVENANCE.md` says it is
pdfcer's own art under the project licence needs neither entry — the shipped
`LICENSE` already covers it and there is no third-party grant to reproduce.
The GUI icon set is exactly this case. In the engine, check 4 flagged that set
on its first run before the exemption existed; that was a false positive, and
a gate that fires on a correct state is one people learn to ignore.

Check 3 is deliberately loose — the goal is to catch a directory that quietly
gained twenty model files under a provenance note describing three fonts, not
to demand a table row per icon.

TWO CHECKS THE ENGINE HAS NO NEED FOR
=====================================

6. **The notice must actually be in the package.** `tools/package-portable.py`
   copies a declared list of documents into the portable folder. A
   `THIRD_PARTY_LICENSES.md` that exists in the repository and is not in that
   list ships to nobody, and looks exactly like one that does.

7. **The generated notice must not have drifted from its template.** The
   static epilogue in `about.hbs` — everything from the `STATIC-EPILOGUE-BEGIN`
   marker to end of file — is literal text, so it must appear verbatim in
   `THIRD_PARTY_LICENSES.md`. If it does not, somebody edited the template and
   never regenerated, and the release carries a notice missing the very
   section that was just written.

   `HANDOFF.md` §10 records exactly this failure mode for a different
   generated file: the RON manifest "has no compiler behind it and no failure
   until someone else runs the round-trip", and it has now been found stale
   twice in one day. A generated compliance artifact deserves better than
   somebody remembering.

WHY NOT JUST TRUST A REVIEWER
=============================

Because the failure is silent and delayed. A model file added today ships in
every release from now on; the moment anyone notices is after distribution,
and un-distributing is not a thing. A gate costs one CI second.

★ WHY THIS GATE IS PYTHON WHEN EVERY OTHER GATE HERE IS BASH
============================================================

Stated because the inconsistency is real and someone will want to fix it.

Checks 6 and 7 are the two that make this gate worth having in a repository
whose own asset directory is the operator's own art and therefore exempt from
most of the others. Check 6 has to read **`PAYLOAD_DOCS` and
`PAYLOAD_ASSET_DIRS` out of `tools/package-portable.py`**, which is Python
source. This file imports that module and reads the actual list objects, so
the check is exact: renaming a constant raises `AttributeError` and fails the
gate loudly, and restructuring the list into a tuple or a dict still works.

The bash alternative is a `grep` for a bracketed list, and a grep that stops
matching prints exactly what a clean run prints — which is the single failure
mode every gate in this directory was written to avoid. `check-ui-strings.sh`
records a sibling gate that "would print `ui-strings: clean` while checking a
handful of files"; a grep over a Python list would be the same defect wearing
a different hat.

So: bash where the check IS a grep over source, Python where the check is
"what does this program's data structure actually say". The engine's copy of
this gate is Python for its own reasons and the convention is at least shared
across the two repositories rather than split within one.

`check-shipped-assets.sh` is a three-line wrapper that finds an interpreter
and reports a SKIP with the real reason if there is none, so `run-all.sh`
invokes this gate exactly like every other.

USAGE / EXIT CODES
==================

  tools/gates/check-shipped-assets.py              the real run
  tools/gates/check-shipped-assets.py --self-test  prove the gate bites

  0 — every redistributed asset records its licensing, and that record reaches
      both the package and the running program.
  1 — at least one does not. The offending directory is named, with what is
      missing and what to do about it.
  2 — PRECONDITION ABSENT (a SKIP, not a pass): this is not the workspace
      root, or a declared engine directory's tree is not mounted. `run-all.sh`
      renders 2 as SKIPPED and refuses to call the overall run a pass.
"""


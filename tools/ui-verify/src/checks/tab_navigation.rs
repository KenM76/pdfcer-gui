//! `tab_moves_between_form_fields` — **Tab pressed inside a form field goes to
//! the next field, not into the ribbon** — `OPERATOR_REQUESTS.md` O204.
//! Driven off-screen with the scripted pointer, whose keys enter the frame
//! ahead of the `app::keyclaim` plugin exactly as a real keyboard's do.
//!
//! Design and rationale: `docs/modules/ui-verify/checks/tab_navigation.md`.

use super::dimdrive::launch_path;
use crate::checks::driving;
use crate::checks::{Check, CheckContext};
use crate::coords::{CanvasMapping, DocPoint, PageGeometry};
use crate::error::{Error, Result};
use crate::input::scripted::ScriptedPointer;
use crate::launch::Session;
use crate::report::CheckReport;
use crate::trace::Trace;

/// Filling a field is not mode-gated; Read is the shell's quietest mode.
const MODE: &str = "mode.read"; // ui-text-exempt: a command id, never displayed
/// Three fillable text fields — two cannot tell a step from a wrap.
const FIXTURE: &str = "three-text-fields.pdf";
const FIXTURE_METHOD: &str = "It is generated by its PROVENANCE script in `fixtures/`.";

/// The fillable census — one line per box this canvas will let him type into.
const BOX_LINE: &str = "form-box";
/// A text field took the keyboard.
const FOCUS: &str = "form-focus";
/// The `app::keyclaim` plugin took a Tab press for a canvas ring.
const CLAIM: &str = "tab-claim";
/// The field ring spent one.
const MOVED: &str = "tab-field";
/// The ring had exactly one stop, so the press was spent and focus did not
/// move. Correct behaviour, and useless evidence — reported as a SKIP.
const ALONE: &str = "tab-field-alone";

/// See the module documentation.
pub struct TabMovesBetweenFormFields;

impl Check for TabMovesBetweenFormFields {
    fn name(&self) -> &'static str {
        "tab_moves_between_form_fields"
    }

    fn defect(&self) -> &'static str {
        "Tab pressed while filling a form field walks egui's own focus ring into the ribbon \
         instead of moving to the next field, because `Focus::begin_pass` latches the move out \
         of `RawInput` before any application code runs. Invisible to a unit test of the ring: \
         the ring steps correctly and never receives the press"
    }

    fn run(&self, ctx: &CheckContext) -> CheckReport {
        let mut report = CheckReport::new(self.name(), self.defect());
        match drive(ctx, &mut report) {
            Ok(Some(failure)) => report.fail(failure),
            Ok(None) => report.pass(),
            Err(why) => report.from_error(&why),
        }
    }
}

/// One `form-box` census line, parsed back into a canvas-space centre.
struct Fillable {
    page: usize,
    field: String,
    centre: (f64, f64),
}

/// Read the application's own census of where its fillable boxes are.
fn fillable(trace: &Trace) -> Vec<Fillable> {
    trace
        .events(BOX_LINE)
        .filter(|l| l.get("kind") == Some("text"))
        .filter_map(|l| {
            let page = l.get("page")?.parse().ok()?;
            let field = l.get("field")?.to_owned();
            // `rect=(x,y)+(w,h)` — canvas space, as the census writes it.
            let raw = l.get("rect")?;
            let (min, size) = raw.split_once(")+(")?;
            let (x, y) = min.trim_start_matches('(').split_once(',')?;
            let (w, h) = size.trim_end_matches(')').split_once(',')?;
            let (x, y): (f64, f64) = (x.trim().parse().ok()?, y.trim().parse().ok()?);
            let (w, h): (f64, f64) = (w.trim().parse().ok()?, h.trim().parse().ok()?);
            Some(Fillable {
                page,
                field,
                centre: (x + w / 2.0, y + h / 2.0),
            })
        })
        .collect()
}

/// The last `tab-field` move, as `(from, to, backwards)`.
fn last_move(trace: &Trace) -> Option<(String, String, bool)> {
    let line = trace.events(MOVED).last()?;
    Some((
        line.get("from")?.to_owned(),
        line.get("to")?.to_owned(),
        line.get("backwards") == Some("true"),
    ))
}

fn drive(ctx: &CheckContext, report: &mut CheckReport) -> Result<Option<String>> {
    let doc = ctx.out("tab_navigation.pdf");
    let source = match &ctx.pdf {
        Some(pdf) => pdf.clone(),
        None => driving::repo_fixture(FIXTURE, FIXTURE_METHOD)?,
    };
    std::fs::copy(&source, &doc)
        .map_err(|e| Error::new(format!("copying {}: {e}", source.display())))?;
    report.note(format!("document: {}", source.display()));
    let page = crate::fixture::page_geometry(&doc).ok_or_else(|| {
        Error::new(format!(
            "cannot read a page size from {}. SKIPPED.",
            source.display()
        ))
    })?;
    let (session, pointer) = launch_path(ctx, report, doc, MODE, "tab_navigation", &[])?;
    let outcome = measure(ctx, report, &session, &pointer, page);
    let parked = pointer.gone(&session);
    match outcome? {
        Some(failure) => Ok(Some(failure)),
        None => parked.map(|_| None),
    }
}

fn measure(
    ctx: &CheckContext,
    report: &mut CheckReport,
    session: &Session,
    pointer: &ScriptedPointer,
    page: PageGeometry,
) -> Result<Option<String>> {
    session.settle(40);
    let from = match focus_first(ctx, report, session, pointer, page)? {
        Ok(field) => field,
        Err(failure) => return Ok(Some(failure)),
    };
    report.note(format!("the field {from:?} has the keyboard"));
    let moved_from = match forward(session, pointer)? {
        Ok((moved_from, moved_to)) => {
            report.note(format!(
                "Tab moved the keyboard from {moved_from:?} to {moved_to:?}"
            ));
            moved_from
        }
        Err(failure) => return Ok(Some(failure)),
    };
    if let Some(failure) = backward(session, pointer, &moved_from)? {
        return Ok(Some(failure));
    }
    report.note(format!(
        "Shift+Tab returned to {moved_from:?}, with the canvas claiming both presses off \
         egui's focus walk"
    ));
    Ok(None)
}

/// Clicks the first fillable text field; the inner `Err` is a FAIL sentence.
fn focus_first(
    ctx: &CheckContext,
    report: &mut CheckReport,
    session: &Session,
    pointer: &ScriptedPointer,
    page: PageGeometry,
) -> Result<std::result::Result<String, String>> {
    let trace = session.trace()?;
    let boxes = fillable(&trace);
    if boxes.len() < 3 {
        return Err(Error::new(format!(
            "this document publishes {} fillable text box(es) and the check needs at least 3. \
             A ring of two cannot tell \"Tab moved to the next stop\" from \"Tab wrapped\". \
             Reported as a SKIP: that is a property of the document, not the defect under \
             test. Trace: {}.",
            boxes.len(),
            session.trace_path().display()
        )));
    }
    let first = &boxes[0];
    report.note(format!(
        "{} fillable field(s); aiming at {:?} at canvas ({:.1}, {:.1})",
        boxes.len(),
        first.field,
        first.centre.0,
        first.centre.1
    ));
    let mapping = CanvasMapping::from_trace(&trace, &ctx.profile.vocab, page, first.page)?;
    // The census is canvas space; `doc_to_window` takes PDF space. The flip is
    // the mapping's own formula read backwards: `canvas_y = page_height -
    // doc_y`. The fixture is upright.
    let point = mapping.doc_to_window(DocPoint::new(
        first.page,
        first.centre.0,
        page.height_pt - first.centre.1,
    ))?;
    pointer.click(session, point)?;
    session.settle(25);
    let trace = session.trace()?;
    Ok(match trace.events(FOCUS).last() {
        Some(focused) => Ok(focused.get("field").unwrap_or_default().to_owned()),
        None => Err(format!(
            "clicking a fillable text field focused nothing: no `{FOCUS}` line. Everything \
             below is about where Tab goes FROM a focused field, so this is the precondition \
             failing rather than the feature. Trace: {}.",
            session.trace_path().display()
        )),
    })
}

/// Presses Tab; the inner `Ok` is `(from, to)`, the inner `Err` a FAIL sentence.
fn forward(
    session: &Session,
    pointer: &ScriptedPointer,
) -> Result<std::result::Result<(String, String), String>> {
    pointer.key(session, None, "Tab", None)?;
    session.settle(25);
    let trace = session.trace()?;
    let path = session.trace_path().display();
    if !trace.events(CLAIM).any(|l| l.get("scope") == Some("field")) {
        return Ok(Err(format!(
            "Tab was pressed with a form field focused and the canvas never claimed it: no \
             `{CLAIM} scope=field` line. This is the operator's report verbatim — the press went \
             to egui's own focus walk, which hands it to the first focusable widget of the \
             frame, and that is the ribbon. Look at `canvas::tabnav::claim` and whether the \
             `app::keyclaim` plugin still calls it. Trace: {path}."
        )));
    }
    if trace.events(ALONE).next().is_some() {
        return Err(Error::new(format!(
            "the ring reported itself as having one stop (`{ALONE}`). The press was claimed and \
             spent correctly, so this is not a defect — but it measures nothing about \
             stepping. Reported as a SKIP. Trace: {path}."
        )));
    }
    let Some((from, to, backwards)) = last_move(&trace) else {
        return Ok(Err(format!(
            "the canvas claimed the Tab press and the field ring never spent it: no `{MOVED}` \
             line, so Tab now does nothing at all inside a form. Look for \
             `tab-field-unfocused` or `tab-field-unringed` in the trace: {path}."
        )));
    };
    if backwards {
        return Ok(Err(format!(
            "a bare Tab moved the ring BACKWARDS: `{MOVED} backwards=true`. The two arms are \
             crossed in `canvas::tabnav::claim`, or the press arrived carrying Shift. Trace: \
             {path}."
        )));
    }
    if to == from {
        return Ok(Err(format!(
            "Tab left the focus where it was: `{MOVED} from={from} to={to}`. Trace: {path}."
        )));
    }
    Ok(Ok((from, to)))
}

/// Presses Shift+Tab and requires it to undo the forward step.
fn backward(
    session: &Session,
    pointer: &ScriptedPointer,
    moved_from: &str,
) -> Result<Option<String>> {
    let before = session.trace()?.events(MOVED).count();
    pointer.key(session, None, "Tab", Some("shift"))?;
    session.settle(25);
    let trace = session.trace()?;
    let path = session.trace_path().display();
    let Some(line) = trace.events(MOVED).skip(before).last() else {
        return Ok(Some(format!(
            "Shift+Tab spent nothing: no further `{MOVED}` line after the forward step worked. \
             Half the request — *\"it should tab forward and shift-tab backwards\"*. \
             `canvas::tabnav::claim` matches `shift_only()`; if the modifier arrived as \
             something else the press was left to egui. Trace: {path}."
        )));
    };
    if line.get("backwards") != Some("true") {
        return Ok(Some(format!(
            "Shift+Tab stepped FORWARD: `{}`. The press was claimed and spent, and the \
             direction was lost between the modifier and the ring. Trace: {path}.",
            line.raw
        )));
    }
    let returned = line.get("to").unwrap_or_default();
    if returned != moved_from {
        return Ok(Some(format!(
            "Shift+Tab went backwards and landed on {returned:?}, not back on {moved_from:?} \
             where the forward step came from: the ring's two directions disagree about the \
             order. Trace: {path}."
        )));
    }
    Ok(None)
}
